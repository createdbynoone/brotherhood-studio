#!/usr/bin/env python3
"""Regenerates qml/components/Icons.qml from the @phosphor-icons/web CSS.
   npm pack @phosphor-icons/web@2.1.2 && tar xzf *.tgz && python3 tools/gen_icons.py package/src
Add icon names to WANT to expose more glyphs."""
import re, sys, pathlib

WANT = """gear magnifying-glass folder-plus trash arrow-clockwise sidebar-simple squares-four
clock-counter-clockwise arrow-counter-clockwise sparkle lightning check check-circle warning warning-circle
x x-circle caret-left caret-right caret-down caret-up copy image plus arrows-out film-strip play arrow-up
approximate-equals archive-box circle-dashed command download-simple arrow-square-out upload-simple note-pencil
tag stack funnel sliders-horizontal eye star key lock-simple folder-open arrow-right arrow-left minus dots-three
magic-wand info clipboard-text paper-plane-tilt arrow-up-right columns rows sidebar square-half x-square
image-square prohibit trash-simple export file-image arrows-in-simple arrow-fat-up swap list-magnifying-glass""".split()

base = pathlib.Path(sys.argv[1])
css = (base / "regular/style.css").read_text()
codes = dict(re.findall(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
missing = [w for w in WANT if w not in codes]
if missing:
    print("missing:", missing)
out = ['pragma Singleton', 'import QtQuick', '',
       '// Phosphor Icons (MIT), files in resources/fonts. Generated by tools/gen_icons.py. Do not edit by hand.',
       'QtObject {', '    readonly property var map: ({']
out.append(",\n".join(f'        "{w}": "\\u{codes[w]}"' for w in WANT if w in codes))
out += ['    })', '    function glyph(name) { return map[name] || "" }', '}']
(pathlib.Path(__file__).resolve().parent.parent / "qml/components/Icons.qml").write_text("\n".join(out) + "\n")
print(len(WANT) - len(missing), "icons written")
