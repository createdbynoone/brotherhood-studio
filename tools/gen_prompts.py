#!/usr/bin/env python3
"""Regenerates src/prompt/prompts.cpp from the Swift build's Prompts.swift so both
ports (and the Electron app) keep byte-identical system prompts."""
import re, sys, pathlib
sys.exit("OBSOLETE: prompts.cpp is maintained by hand now (the Swift/Electron sources are gone). Running this would overwrite it.")
root = pathlib.Path(__file__).resolve().parent.parent
swift = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / "Brotherhood Studio/Studio/Prompt/Services/Prompts.swift"
src = swift.read_text()

def literal(name):
    m = re.search(r'static let ' + name + r' = (#?)"""\n(.*?)\n[ \t]*"""#?', src, re.S)
    assert m, name
    body = m.group(2)
    if not m.group(1):
        assert "\\" not in body, name + " has escapes"
    assert ')PROMPT"' not in body
    return body

out = ['// Generated by tools/gen_prompts.py from Prompts.swift. Do not edit by hand.',
       '#include "prompts.h"', '', 'namespace Prompts {']
for n in ["system", "engineNote", "referenceProtocol", "briefSystem"]:
    out.append(f'const QString {n} = QString::fromUtf8(R"PROMPT({literal(n)})PROMPT");')
out.append('}')
(root / "src/prompt/prompts.cpp").write_text("\n".join(out) + "\n")
print("prompts.cpp written")
